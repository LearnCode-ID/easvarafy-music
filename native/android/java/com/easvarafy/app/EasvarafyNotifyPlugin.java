package com.easvarafy.app;

import android.app.Activity;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.os.Build;
import android.text.TextUtils;
import com.getcapacitor.JSArray;
import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;
import java.util.ArrayList;
import java.util.List;

/**
 * Bridge for broadcast notifications (lib/native/notifications.ts).
 *
 * JS -> native: getDeviceId(), configure({ supabaseUrl, anonKey, enabled }),
 *               getStatus(), requestPermission(), show({ id, title, body,
 *               imageUrl, actionUrl }), markSeen({ ids }), pollNow()
 * native -> JS: "notificationOpened" { id, actionUrl } (retained until the
 *               web layer attaches its listener, so cold starts work too)
 */
@CapacitorPlugin(name = "EasvarafyNotify")
public class EasvarafyNotifyPlugin extends Plugin {
    private static volatile EasvarafyNotifyPlugin active = null;
    private static JSObject pendingOpen = null;

    @Override
    public void load() {
        active = this;
        JSObject pending;
        synchronized (EasvarafyNotifyPlugin.class) {
            pending = pendingOpen;
            pendingOpen = null;
        }
        if (pending != null) notifyListeners("notificationOpened", pending, true);
    }

    @Override
    protected void handleOnDestroy() {
        if (active == this) active = null;
    }

    /** Called by MainActivity for launch / onNewIntent intents. */
    public static void dispatchOpenIntent(Intent intent) {
        if (intent == null || !BroadcastNotifier.ACTION_OPEN.equals(intent.getAction())) return;
        JSObject data = new JSObject();
        String id = intent.getStringExtra(BroadcastNotifier.EXTRA_ID);
        String actionUrl = intent.getStringExtra(BroadcastNotifier.EXTRA_ACTION_URL);
        if (id != null) data.put("id", id);
        if (actionUrl != null) data.put("actionUrl", actionUrl);
        // Consume so a configuration change does not re-open it.
        intent.setAction(Intent.ACTION_MAIN);
        EasvarafyNotifyPlugin plugin = active;
        if (plugin != null) {
            plugin.notifyListeners("notificationOpened", data, true);
        } else {
            synchronized (EasvarafyNotifyPlugin.class) {
                pendingOpen = data;
            }
        }
    }

    @PluginMethod
    public void getDeviceId(PluginCall call) {
        JSObject ret = new JSObject();
        ret.put("deviceId", BroadcastNotifier.getOrCreateDeviceId(getContext()));
        call.resolve(ret);
    }

    @PluginMethod
    public void configure(PluginCall call) {
        String url = call.getString("supabaseUrl", "");
        String anon = call.getString("anonKey", "");
        boolean enabled = Boolean.TRUE.equals(call.getBoolean("enabled", true));
        BroadcastNotifier.configure(getContext(), url, anon, enabled);
        boolean scheduled = false;
        if (enabled && BroadcastNotifier.isConfigured(getContext())) {
            scheduled = NotificationPollJobService.schedule(getContext());
        } else if (!enabled) {
            NotificationPollJobService.cancel(getContext());
        }
        JSObject ret = new JSObject();
        ret.put("scheduled", scheduled);
        call.resolve(ret);
    }

    private String permissionState() {
        if (BroadcastNotifier.notificationsAllowed(getContext())) return "granted";
        if (Build.VERSION.SDK_INT >= 33) {
            Activity activity = getActivity();
            if (activity != null
                && activity.checkSelfPermission("android.permission.POST_NOTIFICATIONS") != PackageManager.PERMISSION_GRANTED) {
                return "prompt";
            }
        }
        return "denied";
    }

    private boolean firebaseConfigured() {
        // Generated by the google-services Gradle plugin from google-services.json.
        return getContext().getResources().getIdentifier("google_app_id", "string", getContext().getPackageName()) != 0;
    }

    @PluginMethod
    public void getStatus(PluginCall call) {
        JSObject ret = new JSObject();
        ret.put("permission", permissionState());
        ret.put("firebaseConfigured", firebaseConfigured());
        ret.put("pollerScheduled", NotificationPollJobService.isScheduled(getContext()));
        ret.put("deviceId", BroadcastNotifier.getOrCreateDeviceId(getContext()));
        call.resolve(ret);
    }

    @PluginMethod
    public void requestPermission(PluginCall call) {
        Activity activity = getActivity();
        if (Build.VERSION.SDK_INT >= 33 && activity != null
            && activity.checkSelfPermission("android.permission.POST_NOTIFICATIONS") != PackageManager.PERMISSION_GRANTED) {
            activity.requestPermissions(new String[] { "android.permission.POST_NOTIFICATIONS" }, 4213);
        }
        JSObject ret = new JSObject();
        ret.put("permission", permissionState());
        call.resolve(ret);
    }

    @PluginMethod
    public void show(final PluginCall call) {
        final String id = call.getString("id", "");
        final String title = call.getString("title", "");
        final String body = call.getString("body", "");
        final String imageUrl = call.getString("imageUrl", null);
        final String actionUrl = call.getString("actionUrl", null);
        if (TextUtils.isEmpty(id) || TextUtils.isEmpty(title)) {
            call.reject("id and title are required");
            return;
        }
        new Thread(() -> {
            boolean shown = BroadcastNotifier.show(getContext(), id, title, body, imageUrl, actionUrl);
            JSObject ret = new JSObject();
            ret.put("shown", shown);
            call.resolve(ret);
        }, "easvarafy-notify-show").start();
    }

    @PluginMethod
    public void markSeen(PluginCall call) {
        JSArray ids = call.getArray("ids");
        List<String> list = new ArrayList<>();
        if (ids != null) {
            for (int i = 0; i < ids.length(); i++) {
                String id = ids.optString(i, null);
                if (id != null) list.add(id);
            }
        }
        BroadcastNotifier.markSeen(getContext(), list);
        call.resolve();
    }

    @PluginMethod
    public void pollNow(final PluginCall call) {
        new Thread(() -> {
            BroadcastNotifier.pollOnce(getContext());
            call.resolve();
        }, "easvarafy-notify-poll-now").start();
    }
}
